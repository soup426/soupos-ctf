#include "idt.h"
#include "isr.h"

typedef struct {
    uint16_t base_low;   /* bits 0-15 of handler address  */
    uint16_t sel;        /* code segment selector          */
    uint8_t  zero;       /* always 0                       */
    uint8_t  flags;      /* gate type, DPL, present bit    */
    uint16_t base_high;  /* bits 16-31 of handler address  */
} __attribute__((packed)) idt_entry_t;

typedef struct {
    uint16_t limit;
    uint32_t base;
} __attribute__((packed)) idt_ptr_t;

static idt_entry_t idt[256];
static idt_ptr_t   idt_ptr;

/* I/O port helpers */
static inline void outb(uint16_t port, uint8_t val) {
    __asm__ volatile ("outb %0, %1" : : "a"(val), "Nd"(port));
}
static inline uint8_t inb(uint16_t port) {
    uint8_t ret;
    __asm__ volatile ("inb %1, %0" : "=a"(ret) : "Nd"(port));
    return ret;
}

void idt_set_gate(uint8_t num, uint32_t handler, uint16_t sel, uint8_t flags) {
    idt[num].base_low  = (uint16_t)(handler & 0xFFFF);
    idt[num].base_high = (uint16_t)((handler >> 16) & 0xFFFF);
    idt[num].sel       = sel;
    idt[num].zero      = 0;
    /* flags: 0x8E = 1000_1110b = present, ring 0, 32-bit interrupt gate */
    idt[num].flags     = flags;
}

/* Remap the 8259 PIC so IRQs 0-15 -> vectors 32-47 (above CPU exceptions) */
static void pic_remap(void) {
    /* Save masks */
    uint8_t mask1 = inb(0x21);
    uint8_t mask2 = inb(0xA1);

    /* ICW1: start init sequence, expect ICW4 */
    outb(0x20, 0x11);
    outb(0xA0, 0x11);

    /* ICW2: vector offsets */
    outb(0x21, 0x20);   /* master: IRQ0 -> vector 32 */
    outb(0xA1, 0x28);   /* slave:  IRQ8 -> vector 40 */

    /* ICW3: cascade wiring */
    outb(0x21, 0x04);   /* master has slave on IRQ2 */
    outb(0xA1, 0x02);   /* slave's cascade identity = 2 */

    /* ICW4: 8086 mode */
    outb(0x21, 0x01);
    outb(0xA1, 0x01);

    /* Restore masks, but force-unmask IRQ0 (timer) and IRQ1 (keyboard) -
       GRUB may have left them masked and we need them live */
    outb(0x21, mask1 & 0xFC);  /* clear bits 0 and 1 = unmask IRQ0, IRQ1 */
    outb(0xA1, mask2);
}

